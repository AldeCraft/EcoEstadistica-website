/* ===== Accessible theme switch and scroll animations ===== */
(() => {
  const body = document.body;
  const toggle = document.getElementById('themeToggle');
  const icon = toggle?.querySelector('.theme-icon');
  const label = toggle?.querySelector('.theme-label');
  const metaTheme = document.querySelector('meta[name="theme-color"]');
  const applyTheme = (dark) => {
    body.classList.toggle('dark-mode', dark);
    if (toggle) {
      toggle.setAttribute('aria-pressed', String(dark));
      toggle.setAttribute('aria-label', translations[currentLang][dark ? 'theme.light' : 'theme.dark']);
    }
    if (icon) icon.textContent = dark ? '☀' : '☾';
    if (label) label.textContent = translations[currentLang][dark ? 'theme.light' : 'theme.dark'];
    if (metaTheme) metaTheme.setAttribute('content', dark ? '#080a09' : '#123b2a');
  };
  let savedTheme = null;
  try { savedTheme = localStorage.getItem('ecoestadistica-theme'); } catch (_) {}
  applyTheme(savedTheme === 'dark');
  updateThemeLabel();
  toggle?.addEventListener('click', () => {
    const dark = !body.classList.contains('dark-mode');
    applyTheme(dark);
    try { localStorage.setItem('ecoestadistica-theme', dark ? 'dark' : 'light'); } catch (_) {}
  });

  const reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  if (!reduceMotion && 'IntersectionObserver' in window) {
    body.classList.add('js-motion');
    const revealItems = document.querySelectorAll('.section-heading, .category, .panel, .stats-panel, .steps article, .formula, .example-box, footer');
    revealItems.forEach((item, index) => {
      item.setAttribute('data-reveal', '');
      if (item.classList.contains('category') || item.matches('.steps article,.formula')) {
        item.style.setProperty('--reveal-delay', `${(index % 5) * 65}ms`);
      }
    });
    const observer = new IntersectionObserver((entries, obs) => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          entry.target.classList.add('is-visible');
          obs.unobserve(entry.target);
        }
      });
    }, { threshold: 0.12, rootMargin: '0px 0px -35px 0px' });
    revealItems.forEach(item => observer.observe(item));
  }
})();
